const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
const {chromium}=require(process.env.FP_PLAYWRIGHT||'playwright');
const output=process.env.FP_TEST_OUTPUT||path.join(require('node:os').tmpdir(),'freeprompter-ui-validation');
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:process.env.FP_CHROME||undefined});
 try {
 const page=await browser.newPage({viewport:{width:960,height:680}});
 const root=path.resolve(__dirname,'..','ui');
 const styles=['base.css','viewer.css','reading-guide.css'].map(f=>fs.readFileSync(path.join(root,'css',f),'utf8')).join('\n');
 await page.setContent(`<style>${styles}</style><div id="root" class="vroot"><div class="vmirror"><div class="vstage"><div class="vtrack"></div></div><div class="vguide"></div></div></div>`);
 await page.addScriptTag({path:path.join(root,'js','reading-guide.js')});
 const result=await page.evaluate(()=>{
  let assertions=0;
  const check=(condition,message)=>{if(!condition)throw Error(message);assertions++;};
  const root=document.querySelector('.vroot'),mirror=root.firstElementChild,track=document.querySelector('.vtrack'),layer=document.querySelector('.vguide');
  root.style.cssText='position:relative;width:900px;height:600px;--bgc:#000;--fgc:#fff;--fs:36px;--k:1;--osc:1;--lh:1.5;--fw:500;--ff:Arial;--align:left;--px:8%;--pg:.4em';
  const text='完整的一行阅读提示应当跟随实际折行，并在滚动后仍然准确。';
  track.innerHTML='<p>'+text.repeat(70)+'</p><p><strong>重点</strong> 与 <em>强调</em> 在同一行</p>';
  const api=FPReadingGuide.create({root,track,layer});
  api.configure({showGuide:true,guideMode:'invert',anchorY:50});
  const lines=api.measure();
  check(lines.length>50,'must cache all wrapped lines, including far below viewport');
  check(lines.at(-1).top>600,'offscreen tail must be cached');
  let index=api.paint(0);
  const firstIndex=index;
  const initialHeight=Number.parseFloat(layer.querySelector('.rg-band').style.height);
  check(initialHeight>20&&initialHeight<60,'one glyph row, not whole paragraph');
  check(layer.style.mixBlendMode==='difference','blend on layer, outside its stacking context');
  const y=lines.at(-6).center-300;
  track.style.transform=`translateY(${-y}px)`;
  index=api.paint(y);
  check(index>lines.length-10,'seeking far beyond first screen must select tail');
  const remeasured=api.measure();
  check(remeasured.length===lines.length,'scroll remeasure count');
  check(remeasured.every((line,i)=>Math.abs(line.top-lines[i].top)<.1),'scroll remeasure coordinates invariant');
  root.style.transform='scale(.6)';root.style.transformOrigin='top left';
  mirror.style.transform='scale(-1.25,-1.25)';
  const mirrored=api.measure();
  check(mirrored.every((line,i)=>Math.abs(line.top-lines[i].top)<.1),'parent scale + mirrorV content coordinates invariant');
  api.paint(y);
  const band=layer.querySelector('.rg-band');
  check(Math.abs(Number.parseFloat(band.style.top)-(lines[index].top-y))<.1,'mirrored current band aligned');
  api.configure({showGuide:true,guideMode:'triangle',guideOpacity:20,guideSize:12});api.paint(y);
  const arrow=layer.querySelector('.rg-arrow-left');
  check(arrow.style.opacity==='0.2','subtle alpha');
  api.configure({showGuide:true,guideMode:'triangle',guideOpacity:90,guideSize:30});api.paint(y);
  check(arrow.style.opacity==='0.9','paused alpha changes');
  check(Math.abs(parseFloat(arrow.style.height)-30*600/1080)<.01,'paused size changes');
  const identity=[...layer.children];
  let mutations=0;const observer=new MutationObserver(records=>{mutations+=records.filter(r=>r.type==='childList').length;});observer.observe(layer,{childList:true});
  for(let i=0;i<500;i++)api.paint(y+i/10);
  mutations+=observer.takeRecords().length;observer.disconnect();
  check(identity.every((node,i)=>layer.children[i]===node),'animation reuses DOM nodes');
  check(mutations===0,'animation never changes child list');
  track.style.fontSize='48px';track.style.lineHeight='1.9';
  const larger=api.measure();
  check(larger.length>lines.length,'font change recomputes wrapping');
  api.configure({showGuide:false});api.paint(y);
  check(!layer.classList.contains('rg-active'),'off hidden');
  track.textContent=' \n\n';api.configure({showGuide:true,guideMode:'invert'});
  check(api.measure().length===0&&api.paint(0)===-1,'empty has no marker');
  // A fresh black/white fixture is captured for a real compositing pixel check.
  root.style.transform='none';mirror.style.transform='none';track.style.transform='none';
  track.style.fontSize='36px';track.style.lineHeight='1.5';track.style.paddingTop='200px';
  track.innerHTML='<p>READ THIS LINE 阅读提示</p>';
  api.configure({showGuide:true,guideMode:'invert',anchorY:40});api.measure();api.paint(0);
  window.__blendBox=layer.querySelector('.rg-band').getBoundingClientRect().toJSON();
  return {assertions,cachedLines:lines.length,firstIndex,tailIndex:index,domMutations:mutations,blendBox:window.__blendBox};
 });
 fs.mkdirSync(output,{recursive:true});
 await page.screenshot({path:path.join(output,'reading-guide-blend.png')});
 fs.writeFileSync(path.join(output,'reading-guide-unit.json'),JSON.stringify(result,null,2));
 assert(result.assertions>=16);console.log('PASS reading guide:',JSON.stringify(result));
 } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
