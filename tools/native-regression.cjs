const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {chromium}=require(process.env.FP_PLAYWRIGHT || 'playwright');
const passed=[];
let connection;
const ok=(name)=>{passed.push(name);console.log('PASS '+name);};
(async()=>{
 const b=await chromium.connectOverCDP('http://127.0.0.1:9223');
 connection=b;
 const pages=()=>b.contexts().flatMap(c=>c.pages());
 const consolePage=pages().find(p=>p.url().includes('console.html'));
 assert(consolePage);
 await consolePage.waitForFunction(()=>FP.snap?.settings.scriptText.length>0);
 const errors=[];
 consolePage.on('pageerror',e=>errors.push(String(e)));
 await consolePage.locator('[data-act="monitor"]').click();
 await consolePage.locator('[data-over-open="main"]').click();
 let output,monitor;
 for(let i=0;i<30;i++){
  output=pages().find(p=>p.url().includes('prompter.html'));
  monitor=pages().find(p=>p.url().includes('monitor.html'));
  if(output&&monitor)break;
  await consolePage.waitForTimeout(100);
 }
 assert(output&&monitor,'原生进程应有控制台、输出、监控三个 WebView');
 for(const page of [output,monitor]){page.on('pageerror',e=>errors.push(String(e)));await page.waitForFunction(()=>window.FP?.snap);}
 await consolePage.waitForFunction(()=>FP.snap.playback.contentH>FP.snap.playback.viewH);
 ok('真实 Tauri 控制台、提词输出、正像监控三窗口创建');
 await consolePage.locator('#btnPlay').click();
 await output.waitForFunction(()=>FP.snap.playback.playing);
 await monitor.waitForFunction(()=>FP.snap.playback.playing);
 const state=async(p,id)=>p.locator(id).getAttribute('style');
 const before=await Promise.all([state(consolePage,'#pvTrack'),state(output,'#track'),state(monitor,'#mvTrack')]);
 await consolePage.waitForTimeout(1400);
 const after=await Promise.all([state(consolePage,'#pvTrack'),state(output,'#track'),state(monitor,'#mvTrack')]);
 for(let i=0;i<3;i++)assert.notEqual(after[i],before[i]);
 assert(await output.locator('#mirror').evaluate(e=>e.classList.contains('mh')));
 assert(!(await monitor.locator('#mvMirror').evaluate(e=>e.classList.contains('mh'))));
 ok('三窗口连续播放，主持人镜像与导播正像分离');
 await monitor.locator('#mPlay').click();
 await consolePage.waitForFunction(()=>!FP.snap.playback.playing);
 await output.waitForFunction(()=>!FP.snap.playback.playing);
 await consolePage.waitForTimeout(150);
 const paused=await Promise.all([state(consolePage,'#pvTrack'),state(output,'#track'),state(monitor,'#mvTrack')]);
 await consolePage.waitForTimeout(500);
 assert.deepEqual(await Promise.all([state(consolePage,'#pvTrack'),state(output,'#track'),state(monitor,'#mvTrack')]),paused);
 ok('从监控窗口暂停，同步三窗口且暂停无漂移');
 const font=consolePage.locator('.qk[data-q="fontSize"] input');
 await font.fill('86');await font.press('Tab');
 await output.waitForFunction(()=>FP.snap.settings.fontSize===86);
 await monitor.waitForFunction(()=>FP.snap.settings.fontSize===86);
 ok('控制台手输字号经真实 IPC 同步两个窗口');
 await consolePage.locator('[data-act="nextSeg"]').click();
 await consolePage.waitForTimeout(500);
 assert((await consolePage.locator('#stCurrent').innerText()).startsWith('2/'));
 assert.equal(await monitor.locator('#mSeg').innerText(),'2');
 const times=await Promise.all([consolePage.locator('#stRemain').innerText(),output.locator('[data-v="remain"]').last().innerText(),monitor.locator('#mRemain').innerText()]);
 const seconds=s=>s.split(':').reduce((n,v)=>n*60+Number(v),0);
 assert(Math.max(...times.map(seconds))-Math.min(...times.map(seconds))<=1,JSON.stringify(times));
 ok('跳段在缩放预览和监控中一致，三处剩余时间误差≤1秒');
 await consolePage.screenshot({path:path.join(process.env.FP_TEST_OUTPUT || require('node:os').tmpdir(),'native-console.png')});
 await output.screenshot({path:path.join(process.env.FP_TEST_OUTPUT || require('node:os').tmpdir(),'native-output.png')});
 await monitor.screenshot({path:path.join(process.env.FP_TEST_OUTPUT || require('node:os').tmpdir(),'native-monitor.png')});
 await consolePage.locator('[data-act="screens"]').click();
 await consolePage.screenshot({path:path.join(process.env.FP_TEST_OUTPUT || require('node:os').tmpdir(),'native-settings.png')});
 await consolePage.locator('[data-act="closePanel"]').click();
 await consolePage.locator('[data-over-close="main"]').click();
 await consolePage.waitForFunction(()=>!FP.snap.settings.outputs[0].open);
 assert(await consolePage.locator('[data-over-open="main"]').isVisible());
 assert.deepEqual(errors,[]);
 ok('明确撤回输出，状态同步且无前端异常');
 fs.writeFileSync(path.join(process.env.FP_TEST_OUTPUT || require('node:os').tmpdir(),'native-results.json'),JSON.stringify({passed,times,monitors:await consolePage.evaluate(()=>FP.snap.monitors)},null,2));
 await b.close();
})().catch(async e=>{console.error(e.stack);process.exitCode=1;await connection?.close().catch(()=>{});});
